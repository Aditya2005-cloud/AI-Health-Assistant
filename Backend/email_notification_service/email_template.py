def _is_emergency(patient_data: dict) -> bool:
    """
    Return True if any emergency keyword appears in the combined
    symptoms_description, symptom_tags, or ai_assessment fields.
    """
    combined = " ".join([
        str(patient_data.get("symptoms_description", "")),
        str(patient_data.get("symptom_tags", "")),
        str(patient_data.get("ai_assessment", "")),
    ]).lower()

    for kw in _EMERGENCY_KEYWORDS:
        if kw in combined:
            logger.warning(
                "[EmailTemplate] Emergency keyword '%s' detected - switching to emergency email.", kw
            )
            return True
    return False


