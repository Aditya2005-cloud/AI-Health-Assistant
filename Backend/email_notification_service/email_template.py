def _build_condition_summary(ai_assessment: str, symptoms: str) -> tuple:
    """
    Condition Summary section.
    Returns: (plain_text_str, html_str)
    """
    clean = (
        str(ai_assessment)
        .replace("**", "").replace("*", "").replace("#", "").replace("`", "")
        .strip()
    )

    body_text = clean if clean else (
        "This may be related to the symptoms you reported. "
        "A thorough in-person examination is needed to determine the cause."
    )

    # 1. Plain Text
    text = "\n".join([
        f"\n{_SEP}\nCONDITION SUMMARY\n{_SEP}",
        "",
        "Based on what you have described, this could indicate the following:",
        "",
        body_text,
        "",
        "Please note: This is not a confirmed diagnosis. Only a licensed physician",
        "can diagnose a medical condition after a proper clinical examination.",
    ])

    # 2. HTML
    html = f"""
    <div style="margin-bottom:24px;padding:20px;background-color:#ffffff;border:1px solid #e2e8f0;border-left:4px solid #0d9488;border-radius:8px;">
        <h2 style="margin:0 0 14px 0;font-size:17px;font-weight:700;color:#0f766e;letter-spacing:-0.3px;">🩺 Condition Summary</h2>
        <p>Based on the symptoms you reported, this may indicate the following:</p>
        <p style="background-color: #f8fafc; padding: 15px; border-radius: 6px; border: 1px solid #e2e8f0; font-style: italic; color: #1e293b;">
            "{body_text}"
        </p>
        <p style="font-size: 13px; color: #64748b; margin-top: 12px; line-height: 1.4;">
            <strong>Please note:</strong> This is an initial AI intake analysis and is not a confirmed medical diagnosis. A clinical assessment by a licensed provider is required to determine your diagnosis.
        </p>
    </div>
    """

    return text, html


def _build_medicine_section(ai_assessment: str, medical_history: str, allergies: str) -> tuple:
    """
    Medicine Suggestions section.
    - OTC / wellness only
    - Dosage line defers to doctor/pharmacist
    - Allergy conflict checks
    Returns: (plain_text_str, html_str)
    """
    # Plain text setup
    text_lines = [
        f"\n{_SEP}\nMEDICINE SUGGESTIONS\n{_SEP}",
        "",
        "The following are general over-the-counter (OTC) wellness suggestions",
        "that may provide relief. These are NOT prescriptions.",
        "",
        "IMPORTANT: Confirm all medicines with your doctor or pharmacist before",
        "taking them, especially if you have existing health conditions.",
        "",
    ]

    # HTML setup
    html_header = """
    <div style="margin-bottom:24px;padding:20px;background-color:#ffffff;border:1px solid #e2e8f0;border-left:4px solid #0d9488;border-radius:8px;">
        <h2 style="margin:0 0 14px 0;font-size:17px;font-weight:700;color:#0f766e;letter-spacing:-0.3px;">💊 Medicine Suggestions (OTC Only)</h2>
        <p style="font-size: 13px; color: #64748b; margin-bottom: 15px;">
            The following list highlights common over-the-counter (OTC) support products related to your described symptoms. <strong>These are NOT prescriptions.</strong> Verify all choices with a doctor or pharmacist.
        </p>
    """
    html_items = []

    # OTC map: (symptom keyword, medicine suggestion, allergy-safe alternative)
    otc_map = [
        ("fever",       "Paracetamol (e.g. Dolo 650 or Crocin 650)",               "Ibuprofen (after meals, if no stomach issues)"),
        ("pain",        "Paracetamol (e.g. Dolo 650)",                             "Topical diclofenac gel for localised pain"),
        ("headache",    "Paracetamol (e.g. Dolo 650)",                             "Cold compress on forehead"),
        ("cold",        "Strepsils lozenges for throat soothing",                  "Honey and warm water gargle"),
        ("cough",       "ORS (Electral) to stay hydrated during cough",            "Warm turmeric milk"),
        ("sore throat", "Strepsils lozenges",                                      "Warm salt-water gargle"),
        ("acidity",     "Antacid such as Digene or Gelusil MPS (chewed after meals)", "Plain cold milk in small sips"),
        ("indigestion", "Pudin Hara capsules (after meals)",                       "Ajwain (carom seeds) with warm water"),
        ("nausea",      "ORS (Electral) to replace lost fluids",                   "Ginger tea in small sips"),
        ("diarrhea",    "ORS (Electral) - one sachet dissolved in 1 litre of water", "Coconut water for hydration"),
        ("allergic",    "Cetirizine 10mg (e.g. Cetzine) - non-drowsy option: Fexofenadine (Allegra 120)", "Consult your doctor if allergy is severe"),
        ("congestion",  "Saline nasal drops (available without prescription)",     "Steam inhalation with hot water"),
        ("muscle",      "Topical pain relief gel (e.g. Moov or Volini spray)",     "Warm compress on the affected area"),
    ]

    combined_text = f"{ai_assessment} {medical_history}".lower()
    found_any = False

    for keyword, medicine, alternative in otc_map:
        if keyword in combined_text:
            found_any = True
            base_name = medicine.split("(")[0].strip()
            
            # Check for allergy conflict
            is_allergic = _has_allergy_conflict(base_name, allergies) or _has_allergy_conflict(keyword, allergies)
            
            if is_allergic:
                # Text
                text_lines.append(
                    f"  Note: {medicine} was considered for your {keyword} symptoms but\n"
                    f"  may conflict with your recorded allergies.\n"
                    f"  Allergy-safe alternative: {alternative}\n"
                )
                # HTML
                html_items.append(f"""
                <div style="margin-bottom:10px;padding:12px;border:1px solid #e2e8f0;border-left:3px solid #eab308;border-radius:6px;background-color:#fffbeb;">
                    <div style="font-weight:700;font-size:14px;color:#1e293b;" style="color: #854d0e;">⚠️ Allergy Conflict Detected</div>
                    <div style="font-size:13px;color:#64748b;margin-top:4px;" style="margin-top: 4px; color: #a16207;">
                        "{medicine}" was flagged as matching your allergy profile.
                    </div>
                    <div style="font-size:13px;color:#dc2626;margin-top:6px;font-weight:600;">Suggested Allergy-Safe Option: {alternative}</div>
                </div>
                """)
            else:
                # Text
                text_lines.append(f"  {medicine}")
                text_lines.append("  (Dosage: Please confirm with your doctor or pharmacist)\n")
                
                # HTML
                html_items.append(f"""
                <div style="margin-bottom:10px;padding:12px;border:1px solid #e2e8f0;border-left:3px solid #0d9488;border-radius:6px;background-color:#f8fafc;">
                    <div style="font-weight:700;font-size:14px;color:#1e293b;">🔹 {medicine}</div>
                    <div style="font-size:13px;color:#64748b;margin-top:4px;">Dosage: As recommended by doctor/pharmacist. Do not exceed suggested packaging instructions.</div>
                </div>
                """)

    if not found_any:
        text_lines.append(
            "  No specific OTC suggestions matched your symptom description.\n"
            "  Please consult your pharmacist or doctor for personalised guidance."
        )
        html_items.append("""
        <p style="font-style: italic; color: #64748b; font-size: 14px;">
            No specific OTC suggestions matched your symptom description. Please consult a professional.
        </p>
        """)

    text = "\n".join(text_lines)
    html = html_header + "\n".join(html_items) + "\n</div>"
    
    return text, html


def _build_diet_plan(allergies: str) -> tuple:
    """
    Diet Plan section.
    Returns: (plain_text_str, html_str)
    """
    text_lines = [
        f"\n{_SEP}\nDIET PLAN\n{_SEP}",
        "",
        "A balanced, easy-to-digest diet supports recovery. General suggestions:",
        "",
    ]

    html_header = """
    <div style="margin-bottom:24px;padding:20px;background-color:#ffffff;border:1px solid #e2e8f0;border-left:4px solid #0d9488;border-radius:8px;">
        <h2 style="margin:0 0 14px 0;font-size:17px;font-weight:700;color:#0f766e;letter-spacing:-0.3px;">🥗 Diet Plan</h2>
        <p style="font-size: 13px; color: #64748b; margin-bottom: 12px;">Suggested nutrition guidelines for recovery:</p>
        <ul style="padding-left:20px;margin:0 0 15px 0;line-height:1.8;font-size:14px;color:#334155;">
    """
    html_items = []

    suggestions = [
        ("Khichdi",                          "Plain boiled rice with vegetables"),
        ("Fresh fruits",                     "Pomegranate or guava if citrus causes issues"),
        ("Steamed or boiled vegetables",     "Salads with light dressing"),
        ("Yoghurt",                          "Coconut milk-based dishes if dairy is an issue"),
        ("Warm soups and broths",            "Clear vegetable broth"),
        ("Green tea or ginger tea",          "Plain warm water with lemon"),
    ]

    for food, alternative in suggestions:
        if _has_allergy_conflict(food, allergies):
            text_lines.append(f"  Allergy-safe alternative: {alternative}")
            html_items.append(f'<li style="color: #b45309;">⚠️ <strong>Allergy-safe alternative:</strong> {alternative}</li>')
        else:
            text_lines.append(f"  {food}")
            html_items.append(f'<li>{food}</li>')

    text_lines += [
        "",
        "  Foods to limit during this period:",
        "  - Spicy, oily, or heavily processed foods",
        "  - Alcohol and caffeinated drinks (coffee, energy drinks)",
        "  - Raw or unwashed fruits and vegetables",
        "  - High-sugar snacks and sodas",
    ]

    html_limit_section = """
        </ul>
        <p style="font-size: 14px; font-weight: 700; color: #475569; margin: 15px 0 6px 0;">🚫 Foods to Limit:</p>
        <ul style="padding-left:20px;margin:0;line-height:1.8;font-size:14px;color:#64748b;">
            <li>Spicy, deep-fried, or oily meals</li>
            <li>Alcohol, coffee, and energy drinks</li>
            <li>Raw/unwashed produce (ensure everything is fully cooked)</li>
            <li>High-sugar snacks, sweets, and sodas</li>
        </ul>
    </div>
    """

    text = "\n".join(text_lines)
    html = html_header + "\n".join(html_items) + html_limit_section
    return text, html


